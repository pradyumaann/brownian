// Builds supabase/functions/_shared/spec.ts: the guide the intake endpoint serves to the morning routine (GET, with the key).
// Pieces: docs/routine-spec.md (the rules), data/types.ts (the shape), the template's glossary ids, and a trimmed example
// (the real 13 Nov brief as a daily record, each list cut to its first two entries).
//   node scripts/make-spec.mjs          write the file
//   node scripts/make-spec.mjs --check  exit 1 if the committed file is out of date (run by npm run test:backend)
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const root = resolve(".");
const read = (p) => readFileSync(resolve(root, p), "utf8").replace(/\r\n/g, "\n");
const { brief } = await import(pathToFileURL(resolve(root, "data/2026-11-13.ts")).href);
const { TEMPLATE } = await import(pathToFileURL(resolve(root, "supabase/functions/_shared/template.ts")).href);

// The 13 Nov brief as a daily record.
const d = JSON.parse(JSON.stringify(brief));
d.glossToday = Object.fromEntries(Object.entries(d.gloss).map(([k, g]) => [k, g[2]]));
d.holdings = d.holdings.map(({ n, ...rest }) => rest);
for (const k of ["aliases", "defaultHold", "defaultWatch", "method", "gloss"]) delete d[k];

// Trim: top-level lists to two entries (the lede and kpis stay whole), long maps to three keys.
const trimmed = {};
for (const [k, v] of Object.entries(d)) {
  if (k === "lede") trimmed[k] = v;
  else if (Array.isArray(v)) trimmed[k] = v.slice(0, 2);
  else if (v && typeof v === "object" && Object.keys(v).length > 4) trimmed[k] = Object.fromEntries(Object.entries(v).slice(0, 3));
  else trimmed[k] = v;
}

const glossIds = Object.entries(TEMPLATE.gloss)
  .map(([id, e]) => `- \`${id}\`: ${e.term}${e.today !== undefined ? " (fixed line, do not send)" : ""}`)
  .join("\n");

const spec = [
  read("docs/routine-spec.md").trimEnd(),
  "",
  "## The shape (data/types.ts)",
  "",
  "`Brief` below is the full record. The DAILY record is a `Brief` WITHOUT `aliases`, `defaultHold`, `defaultWatch`, `method` and `gloss`; its `holdings` entries are `{ id, d, h, w, t, src }` (no `n`); and it has `glossToday: Record<string, string>`.",
  "",
  "```ts",
  read("data/types.ts").trimEnd(),
  "```",
  "",
  "## Glossary ids for `glossToday`",
  "",
  glossIds,
  "",
  "## Example: the 13 Nov 2026 record, trimmed (every list shows its first two entries; yours has the full set)",
  "",
  "```json",
  JSON.stringify(trimmed, null, 1),
  "```",
  "",
].join("\n");

const out = `// GENERATED by scripts/make-spec.mjs from docs/routine-spec.md, data/types.ts and the template. Do not edit by hand.
export const SPEC: string = ${JSON.stringify(spec)};
`;
const file = resolve(root, "supabase/functions/_shared/spec.ts");

if (process.argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(file, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
  if (cur !== out) { console.error("spec.ts is out of date: run node scripts/make-spec.mjs"); process.exit(1); }
  console.log(`spec.ts is up to date (${spec.length} characters)`);
} else {
  writeFileSync(file, out);
  console.log(`wrote spec.ts: ${spec.length} characters (~${Math.round(spec.length / 4)} tokens)`);
}
